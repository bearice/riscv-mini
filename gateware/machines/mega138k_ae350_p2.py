# CPU-visible DRAM window: the AE350 external AHB slave region.
DDR_WINDOW_BASE = 0xE8000000
DDR_WINDOW_SIZE = 1 << 27

# DDR3 pin map (Tang Mega 138K Pro, vendor ae350_customized_demo.cst).
DDR3_ADDR = 'N1 R1 R2 N2 P1 T2 N4 U1 T4 T3 M1 P4 N3 U2 U5'.split()
DDR3_BA = 'M4 L5 K3'.split()
DDR3_DM = 'F4 H9 E3 A3'.split()
DDR3_DQ = ('G4 J6 L8 G5 K7 J5 K8 K6 E6 H8 H6 G8 D6 F8 G6 F7 '
           'C4 F3 B4 E5 D3 D5 A4 D4 E1 A2 G2 C2 F2 E2 G1 D1').split()
DDR3_DQS = [('J4', 'H4'), ('H7', 'G7'), ('B5', 'A5'), ('C1', 'B1')]
DDR3_CTRL = {'cs_n': 'L4', 'ras_n': 'H2', 'cas_n': 'H1', 'we_n': 'J3',
             'cke': 'L3', 'odt': 'J1', 'reset_n': 'N8'}
DDR3_CK = ('M2', 'L2')

DDR_IP_DIR = os.path.join(os.path.dirname(__file__), '..', 'vendor', 'gowin_ddr3_400')


def _ddr3_io():
    io = []
    for i, pin in enumerate(DDR3_ADDR):
        drive = 12 if i == 14 else 8
        io.append((f'ddr3_addr', i, Pins(pin), IOStandard('SSTL15'),
                   Misc(f'PULL_MODE=NONE DRIVE={drive} BANK_VCCIO=1.5')))
    for i, pin in enumerate(DDR3_BA):
        io.append(('ddr3_ba', i, Pins(pin), IOStandard('SSTL15'),
                   Misc('PULL_MODE=NONE DRIVE=8 BANK_VCCIO=1.5')))
    for name, pin in DDR3_CTRL.items():
        io.append((f'ddr3_{name}', 0, Pins(pin), IOStandard('SSTL15'),
                   Misc('PULL_MODE=NONE DRIVE=8 BANK_VCCIO=1.5')))
    for i, pin in enumerate(DDR3_DM):
        io.append(('ddr3_dm', i, Pins(pin), IOStandard('SSTL15'),
                   Misc('PULL_MODE=NONE DRIVE=8 BANK_VCCIO=1.5')))
    for i, pin in enumerate(DDR3_DQ):
        io.append(('ddr3_dq', i, Pins(pin), IOStandard('SSTL15'),
                   Misc('PULL_MODE=NONE DRIVE=8 BANK_VCCIO=1.5')))
    # Differential clock and strobes are placed by explicit platform commands
    # (single 1-bit port on two pins, SSTL15D), mirroring the vendor cst where
    # the N side is generated by the tool and the IP's *_n output stays unused.
    io.append(('ddr3_ck', 0, Pins('X')))
    io.append(('ddr3_ck_n', 0, Pins('X')))
    for i in range(4):
        io.append((f'ddr3_dqs{i}', 0, Pins('X')))
        io.append((f'ddr3_dqs{i}_n', 0, Pins('X')))
    return io


class FabricUART(LiteXModule):
    """Minimal 8N1 transmitter, used only to probe the console pin path."""
    def __init__(self, pad, clk_hz=100e6, baud=115200, text=b"FABRIC-UART-OK\r\n"):
        div = max(1, int(round(clk_hz / baud)))
        cnt = Signal(max=div)
        tick = Signal()
        byte = Signal(8)
        bitc = Signal(4)
        shift = Signal(10)
        cur = Signal(8)
        self.comb += [tick.eq(cnt == div - 1), cur.eq(0)]
        for i, ch in enumerate(text):
            self.comb += If(byte == i, cur.eq(ch if isinstance(ch, int) else ord(ch)))
        self.sync += If(tick, cnt.eq(0)).Else(cnt.eq(cnt + 1))
        fsm = FSM(reset_state="IDLE")
        self.submodules += fsm
        fsm.act("IDLE",
            pad.eq(1),
            If(tick,
               If(byte >= len(text), NextValue(byte, 0)),
               NextValue(shift, Cat(C(0, 1), cur, C(1, 1))),
               NextValue(bitc, 0),
               NextState("SEND"),
            ),
        )
        fsm.act("SEND",
            pad.eq(shift[0]),
            If(tick,
               NextValue(shift, shift >> 1),
               If(bitc == 9,
                  NextValue(byte, byte + 1),
                  NextState("IDLE"),
               ).Else(NextValue(bitc, bitc + 1)),
            ),
        )


class GowinDDR3(LiteXModule):
    """Gowin_PLL_DDR3 + DDR3_Memory_Interface_Top with an ``ddr`` clock domain."""
    def __init__(self, platform, pads, ck_hz=400e6):
        ui = DDR3UI()
        self.ui = ui
        self.clk_out = Signal()
        self.pll_lock = Signal()
        self.init_calib_complete = Signal()

        clk50 = platform.lookup_request('clk50')
        clk_ref = Signal(name_override='ddr3_clk_ref')
        memory_clk = Signal(name_override='ddr3_memory_clk')
        pll_stop = Signal()
        # Vendor Gowin_PLL_DDR3: 50 MHz in, CLKOUT0 50 MHz (IP reference clock),
        # CLKOUT2 = the DDR clock of the selected IP point.
        self.specials += Instance('Gowin_PLL_DDR3', name='ddr3_pll',
            i_clkin=clk50, i_reset=0,
            i_enclk0=1, i_enclk2=pll_stop,
            o_clkout0=clk_ref, o_clkout2=memory_clk, o_lock=self.pll_lock)
        platform.toolchain.additional_cst_commands.append('INS_LOC "ddr3_pll/PLL_inst" PLL_L[0];')

        self.specials += Instance('DDR3_Memory_Interface_Top', name='ddr3',
            # Clocks / reset / calibration.
            i_clk             = clk_ref,
            i_memory_clk      = memory_clk,
            i_pll_lock        = self.pll_lock,
            o_pll_stop        = pll_stop,
            i_rst_n           = ~ResetSignal('sys'),
            o_clk_out         = self.clk_out,
            o_ddr_rst         = Open(),
            o_init_calib_complete = self.init_calib_complete,
            # User interface.
            o_cmd_ready       = ui.cmd_ready,
            i_cmd             = ui.cmd,
            i_cmd_en          = ui.cmd_en,
            i_addr            = ui.addr,
            o_wr_data_rdy     = ui.wr_data_rdy,
            i_wr_data         = ui.wr_data,
            i_wr_data_en      = ui.wr_data_en,
            i_wr_data_end     = ui.wr_data_end,
            i_wr_data_mask    = ui.wr_data_mask,
            o_rd_data         = ui.rd_data,
            o_rd_data_valid   = ui.rd_data_valid,
            o_rd_data_end     = Open(),
            i_sr_req          = 0,
            i_ref_req         = 0,
            o_sr_ack          = Open(),
            o_ref_ack         = Open(),
            i_burst           = ui.burst,
            # DDR3 pins.
            o_O_ddr_addr      = Cat(pads['addr']),
            o_O_ddr_ba        = Cat(pads['ba']),
            o_O_ddr_cs_n      = pads['cs_n'],
            o_O_ddr_ras_n     = pads['ras_n'],
            o_O_ddr_cas_n     = pads['cas_n'],
            o_O_ddr_we_n      = pads['we_n'],
            o_O_ddr_clk       = pads['ck'],
            o_O_ddr_clk_n     = pads['ck_n'],
            o_O_ddr_cke       = pads['cke'],
            o_O_ddr_odt       = pads['odt'],
            o_O_ddr_reset_n   = pads['reset_n'],
            o_O_ddr_dqm       = Cat(pads['dm']),
            io_IO_ddr_dq      = Cat(pads['dq']),
            io_IO_ddr_dqs     = Cat(pads['dqs']),
            io_IO_ddr_dqs_n   = Cat(pads['dqs_n']),
        )
        platform.toolchain.additional_cst_commands.extend([
            'INS_LOC "ddr3/gw3_top/u_ddr_phy_top/u_dll" DDRDLLM_BL;',
            'INS_LOC "ddr3/gw3_top/u_ddr_phy_top/fclkdiv" LEFTSIDE[4];',
        ])


class DDRSoC(LiteXModule):
    def _select_ip(self, ddr_ck):  # keeps the vendor IP point and its clock together
        if not ddr_ck:
            self.ddr_ip_dir = DDR_IP_DIR
            self.ddr_ck_hz = 400e6
            return
        self.ddr_ck_hz = float(ddr_ck) * 1e6
        self.ddr_ip_dir = os.path.join(os.path.dirname(__file__), '..', 'vendor',
                                       'gowin_ddr3_%d' % int(ddr_ck))

    def __init__(self, board, rom, ddr_ck=None):
        self._select_ip(ddr_ck)
        ae350_map.require()
        resources = board['resources']
        uart = resources['debug_uart']
        jtag = resources['cpu_jtag']
        io = [
            ('clk50', 0, Pins('P16'), IOStandard('LVCMOS33')),
            ('reset_key', 0, Pins('U4'), IOStandard('LVCMOS15')),
            ('serial', 0, Subsignal('rx', Pins(uart['rx'])), Subsignal('tx', Pins(uart['tx'])), IOStandard('LVCMOS33')),
            ('cpu_jtag', 0, Subsignal('tck', Pins(jtag['tck']['pin']), Misc('PULL_MODE=DOWN')),
             Subsignal('tms', Pins(jtag['tms']['pin']), Misc('PULL_MODE=UP')),
             Subsignal('tdi', Pins(jtag['tdi']['pin']), Misc('PULL_MODE=UP')),
             Subsignal('tdo', Pins(jtag['tdo']['pin'])), IOStandard(jtag['io_standard'])),
            ('fan_pwm', 0, Pins('T18'), IOStandard('LVCMOS33')),
        ] + _ddr3_io()
        platform = GowinPlatform(board['reference_part'], io, devicename=board['reference_device'])
        ip_dir = self.ddr_ip_dir
        platform.add_source(os.path.join(ip_dir, 'gowin_pll_ddr3.v'))
        platform.add_source(os.path.join(ip_dir, 'ddr3_memory_interface.v'))
        platform.toolchain.options.update(use_cpu_as_gpio=1, use_mspi_as_gpio=1, use_sspi_as_gpio=1,
                                          place_option=2, route_option=2)
        platform.default_clk_name = 'clk50'
        platform.default_clk_period = 20
        self.platform = platform

        pads = {
            'addr':    [platform.request('ddr3_addr', i) for i in range(15)],
            'ba':      [platform.request('ddr3_ba', i) for i in range(3)],
            'dm':      [platform.request('ddr3_dm', i) for i in range(4)],
            'dq':      [platform.request('ddr3_dq', i) for i in range(32)],
            'dqs':     [platform.request(f'ddr3_dqs{i}') for i in range(4)],
            'dqs_n':   [platform.request(f'ddr3_dqs{i}_n') for i in range(4)],
            'ck':      platform.request('ddr3_ck'),
            'ck_n':    platform.request('ddr3_ck_n'),
        }
        for name in DDR3_CTRL:
            pads[name] = platform.request(f'ddr3_{name}')
        # Manual constraints for the differential ports (Pins('X') above
        # suppresses LiteX's own IO_LOC/IO_PORT lines for them).
        pads['ck'].name_override = 'ddr3_ck'
        pads['ck_n'].name_override = 'ddr3_ck_n'
        platform.add_platform_command('IO_LOC "ddr3_ck" M2,L2;')
        platform.add_platform_command('IO_PORT "ddr3_ck" IO_TYPE=SSTL15D PULL_MODE=NONE DRIVE=8 BANK_VCCIO=1.5;')
        for i, (pp, pn) in enumerate(DDR3_DQS):
            pad = pads['dqs'][i]
            pad.name_override = f'ddr3_dqs{i}'
            pads['dqs_n'][i].name_override = f'ddr3_dqs{i}_n'
            platform.add_platform_command(f'IO_LOC "ddr3_dqs{i}" {pp},{pn};')
            platform.add_platform_command(f'IO_PORT "ddr3_dqs{i}" IO_TYPE=SSTL15D PULL_MODE=NONE DRIVE=8 BANK_VCCIO=1.5;')

        self.crg = ClockReset(platform, fabric_hz=ae350_map.FABRIC_HZ)
        self.cpu = NativeAE350(wrapper=True)
        self.ddr = GowinDDR3(platform, pads, ck_hz=self.ddr_ck_hz)

        # DDR UI clock domain and its asynchronous reset.
        self.cd_ddr = ClockDomain('ddr')
        self.comb += self.cd_ddr.clk.eq(self.ddr.clk_out)
        self.specials += AsyncResetSynchronizer(self.cd_ddr, ~self.ddr.pll_lock | ResetSignal('sys'))
        calib_sys = Signal()
        lock_sys = Signal()
        self.specials += [MultiReg(self.ddr.init_calib_complete, calib_sys, 'sys'),
                          MultiReg(self.ddr.pll_lock, lock_sys, 'sys')]

        # Calibration watchdog and CPU release in the always-running sys domain.
        self.calib_timeout = calib_timeout = Signal()
        self.calib_cycles = calib_cycles = Signal(32)
        cpu_hold = Signal(reset=1)
        wait = Signal(28)
        cycles_latched = Signal()
        self.comb += self.cpu.reset.eq(cpu_hold)
        self.sync += [
            If(~calib_sys,
                If(wait != ae350_map.FABRIC_HZ // 4,
                    wait.eq(wait + 1),
                ).Else(
                    calib_timeout.eq(1),
                ),
            ).Else(
                If(~cycles_latched,
                    calib_cycles.eq(wait),
                    cycles_latched.eq(1),
                ),
            ),
            If(calib_sys | calib_timeout,
                cpu_hold.eq(0),
            ),
        ]

        # Liveness of the DDR UI clock, sampled from the ddr domain.
        alive = Signal(16)
        self.sync.ddr += alive.eq(alive + 1)
        alive_sys = Signal()
        self.specials += MultiReg(alive[10], alive_sys, 'sys')

        self.comb += [self.cpu.ahb_rom.sel.eq(1), self.cpu.ahb_ram.sel.eq(1)]

        sram_bus = AHBInterface(data_width=64, address_width=32)
        ddr_bus = AHBInterface(data_width=64, address_width=32)
        err_bus = AHBInterface(data_width=64, address_width=32)

        # Zero-based DDR and high SRAM: the CPU byte address of a DRAM word is
        # its DRAM offset (no -0x2000 shift), see gateware/machines/ae350_map.py.
        self.sram = AHBMemory(sram_bus, ae350_map.SRAM_SIZE, base=ae350_map.SRAM_BASE)
        self.ddr_port = DDR3AHB(ddr_bus, self.ddr.ui,
                                ready_i=calib_sys,
                                accepted_i=ddr_bus.trans[1],
                                base=ae350_map.DDR_BASE, size=ae350_map.DDR_SIZE)
        self.err = ErrorSlave(err_bus)
        # One interconnect, one address-acceptance rule for every slave: the
        # address, direction and selected slave are captured together at the
        # acceptance edge, and the response mux uses that captured slave.
        self.ic = MemInterconnect(self.cpu.ahb_ram, [
            (ae350_map.DDR_BASE, ae350_map.DDR_SIZE, ddr_bus),
            (ae350_map.SRAM_BASE, ae350_map.SRAM_SIZE, sram_bus),
            (0, 1 << 32, err_bus),
        ])
        self.submodules += self.sram, self.ddr_port, self.err, self.ic

        # Status words readable from the ROM window.
        self.status = status = Signal(32)
        self.comb += status.eq(Cat(
            lock_sys,                     # [0]
            calib_sys,                    # [1]
            calib_timeout,                 # [2]
            alive_sys,                     # [3]
            self.ddr_port.error_sticky,    # [4]
            cpu_hold,                      # [5]
            Constant(0, 2),                # [7:6]
            Constant(0x02, 8),             # [15:8] status format version
            Constant(0, 16),               # [31:16]
        ))
        # Transfer one coherent, held diagnostic snapshot through a request /
        # acknowledge handshake. MultiReg on each live counter bit is unsafe.
        # Only the exported words cross; the full recorder stays in DDR.
        recorder = [self.ddr_port.rec_w, self.ddr_port.rec_w_mask,
                    self.ddr_port.rec_w_data[:32], self.ddr_port.rec_r,
                    self.ddr_port.rec_r_sel[:32], self.ddr_port.rec_r_blk[:32],
                    self.ddr_port.rec_r_blk[32:64],
                    Cat(self.ddr_port.rec_w_n, self.ddr_port.rec_r_n)]
        self.recorder_cdc = BusSynchronizer(256, 'ddr', 'sys')
        self.comb += self.recorder_cdc.i.eq(Cat(*recorder))
        snapshot = [self.recorder_cdc.o[i*32:(i+1)*32] for i in range(8)]
        self.rom = AE350ROM(self.cpu.ahb_rom, 8192, init=rom,
                            status=status, cycles=calib_cycles,
                            debug=self.ddr_port.debug, debug_hi=self.ddr_port.debug_hi,
                            windows=[
                                # Per-transaction recorder (read over CPU JTAG):
                                # -20 write cmd|addr, -24 write byte mask,
                                # -28 write data low word, -32 read cmd|addr,
                                # -36 selected 64-bit beat low word,
                                # -40/-44 returned block words 0 and 1,
                                # -48 write/read counters.
                                (-20, snapshot[0]),
                                (-24, snapshot[1]),
                                (-28, snapshot[2]),
                                (-32, snapshot[3]),
                                (-36, snapshot[4]),
                                (-40, snapshot[5]),
                                (-44, snapshot[6]),
                                (-48, snapshot[7]),
                                # Explicit 16-bit counters for the fabric observer.
                                (-52, snapshot[7][16:32]),
                                (-56, snapshot[7][:16]),
                            ])

        serial = platform.request('serial')
        self.cpu.cpu_params.update(i_UART2_RXD=serial.rx, o_UART2_TXD=serial.tx,
                                   i_RTC_CLK=self.crg.rtc)
        # The configured AE350 subsystem hardens UART2/PIT/GPIO/RTC internally
        # (see gateware/vendor/ae350_soc/riscv_ae350_config.v), so there is no
        # fabric-facing APB port and no port-level peripheral clock enable.
        # Only the sources the configured subsystem actually needs: the
        # embedded SPI-flash/DDR3 paths stay out (their DDR3 IP would collide
        # with the standalone 400 MHz IP instance and they are not enabled).
        soc_sources = ('riscv_ae350_top.v', 'riscv_ae350_soc.v', 'gw_dtcm.v', 'gw_itcm.v')
        for name in soc_sources:
            platform.add_source(str(Path(__file__).resolve().parents[1] / 'vendor' / 'ae350_soc' / name))
        platform.add_verilog_include_path(str((Path(__file__).resolve().parents[1] / 'vendor' / 'ae350_soc')))
        self.cpu.connect_jtag(platform.request('cpu_jtag'))
        platform.add_period_constraint(platform.lookup_request('cpu_jtag').tck, 10000)
        self.comb += platform.request('fan_pwm').eq(1)

        # Extra timing constraints the LiteX backend cannot express:
        # the DDR user clock and memory clock are unrelated to the fabric clocks.
        toolchain = platform.toolchain
        _orig_sdc = toolchain.build_timing_constraints

        def build_timing_constraints(vns):
            name, ext = _orig_sdc(vns)
            extra = [
                'create_clock -name ddr_ui_clk -period %.4f -waveform {0 %.4f} [get_pins {ddr3/gw3_top/u_ddr_phy_top/fclkdiv/CLKOUT}]'
                    % (4000.0 / (self.ddr_ck_hz / 1e6), 2000.0 / (self.ddr_ck_hz / 1e6)),
                'create_clock -name ddr_memory_clk -period %.4f -waveform {0 %.4f} [get_nets {ddr3_memory_clk}]'
                    % (1000.0 / (self.ddr_ck_hz / 1e6), 500.0 / (self.ddr_ck_hz / 1e6)),
                'create_clock -name ddr_clk_ref -period 20 -waveform {0 10} [get_nets {ddr3_clk_ref}]',
                'set_clock_groups -asynchronous '
                '-group [get_clocks {sys_clk}] -group [get_clocks {cpu_clk}] '
                '-group [get_clocks {ddr_ui_clk}] -group [get_clocks {ddr_memory_clk}] '
                '-group [get_clocks {ddr_clk_ref}]',
            ]
            with open(name, 'a') as f:
                f.write('\n' + '\n'.join(extra) + '\n')
            return name, ext

        toolchain.build_timing_constraints = build_timing_constraints
